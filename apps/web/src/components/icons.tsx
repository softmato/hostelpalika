import { Glyph, type GlyphName, type GlyphProps } from "@/components/glyph";

/**
 * The web portal's icons, under the lucide names the code already used, so
 * swapping lucide out only changed import lines. Every one draws one of our own
 * glyphs (`packages/shared/src/constants/glyphs.ts`) — several lucide names land
 * on the same glyph on purpose.
 *
 * New code can use `<Glyph name="…" />` directly; add a name here only when
 * something passes icons around as components.
 */
export type IconProps = Omit<GlyphProps, "name">;
export type IconComponent = ((props: IconProps) => React.JSX.Element) & { displayName?: string };

function icon(name: GlyphName): IconComponent {
  // `className=""` rather than Glyph's own default size: like lucide, an icon
  // with no size class is 24px and takes its size from the class it is given.
  const Icon = ({ className = "", ...props }: IconProps) => <Glyph className={className} name={name} {...props} />;
  Icon.displayName = name;
  return Icon;
}

