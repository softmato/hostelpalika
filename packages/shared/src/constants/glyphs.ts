/**
 * The glyph to draw for a name that may have come from data — a stored store
 * item, a site-config slug, a server-chosen look. Older rows still carry the
 * Ionicons spelling (`bed-outline`), so the suffix is dropped; anything else
 * unknown draws a plain circle instead of taking the screen down.
 */
export function resolveGlyph(name: string): GlyphName {
  if (name in GLYPHS) return name as GlyphName;
  const base = name.replace(/-(outline|sharp)$/, "");
  return base in GLYPHS ? (base as GlyphName) : "ellipse";
}
