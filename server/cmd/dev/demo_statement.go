// statementFile writes an eSewa statement in the app-export format — the real
// export kept in internal/modules/finance/testdata/statements, header, footer
// and all (invented formats broke the parsers before). One credit per open
// seeded bill, "Fund Transferred by <resident>" for what is still owed, plus a
// transfer from a stranger and two of the hostel's own payments. Imported in
// ch 50a, the named credits come up against the right bills and the stranger
// is left for a tap. Read-only on the database.
func (d *demo) statementFile(ctx context.Context, args []string) error {
	out := filepath.Join("..", "marketing", "video", "demo-film", "samples", "esewa-statement.csv")
	if len(args) > 0 && args[0] != "" {
		out = args[0]
	}
	ids, err := d.seededIDs(ctx)
	if err != nil {
		return err
	}
	if len(ids) == 0 {
		return errors.New("no seeded residents: run seed-history first")
	}
	cur, err := d.db.Collection("invoices").Find(ctx, bson.D{{Key: "hostelId", Value: d.hostel}, {Key: "residentId", Value: bson.D{{Key: "$in", Value: ids}}},
		{Key: "status", Value: bson.D{{Key: "$in", Value: bson.A{"OPEN", "PARTIAL", "OVERDUE"}}}}})
	if err != nil {
		return err
	}
	var bills []struct {
		ID       bson.ObjectID `bson:"_id"`
		Resident bson.ObjectID `bson:"residentId"`
		Total    int64         `bson:"totalAmount"`
		Period   *string       `bson:"period"`
	}
	if err := cur.All(ctx, &bills); err != nil {
		return err
	}
	names := map[bson.ObjectID]string{}
	rc, err := d.db.Collection("residents").Find(ctx, bson.D{{Key: "_id", Value: bson.D{{Key: "$in", Value: ids}}}})
	if err != nil {
		return err
	}
	var people []struct {
		ID    bson.ObjectID `bson:"_id"`
		First string        `bson:"firstName"`
		Last  string        `bson:"lastName"`
	}
	if err := rc.All(ctx, &people); err != nil {
		return err
	}
	for _, p := range people {
		names[p.ID] = strings.TrimSpace(p.First + " " + p.Last)
	}
	now := time.Now().In(nepalZone)
	var rows []stmtLine
	for i, b := range bills {
		if len(rows) == 5 {
			break
		}
		var bal struct {
			Settled int64 `bson:"settledAmount"`
		}
		_ = d.db.Collection("invoicebalances").FindOne(ctx, bson.D{{Key: "invoiceId", Value: b.ID}}).Decode(&bal)
		owed := b.Total - bal.Settled
		if owed <= 0 || names[b.Resident] == "" {
			continue
		}
		at := now.Add(-time.Duration(i+1)*17*time.Hour - time.Duration(i*7)*time.Minute)
		rows = append(rows, stmtLine{at: at, desc: "Fund Transferred by " + names[b.Resident], cr: owed, resident: names[b.Resident]})
	}
	if len(rows) == 0 {
		return errors.New("no open seeded bill owes anything")
	}
	rows = append(rows,
		stmtLine{at: now.Add(-30 * time.Hour), desc: "Fund Transferred by Ramila Basnet", cr: 2500},
		stmtLine{at: now.Add(-50 * time.Hour), desc: "Paid for NEA ELECTRICITY", dr: 3420},
		stmtLine{at: now.Add(-9 * time.Hour), desc: "Paid for KHANAL KIRANA STORE", dr: 1850})
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(out, []byte(esewaCSV(rows, now)), 0o644); err != nil {
		return err
	}
	fmt.Printf("%s: %d rows (%d from residents, 1 stranger, 2 debits)\n", out, len(rows), len(rows)-3)
	for _, r := range rows {
		if r.resident != "" {
			fmt.Printf("  Rs %d from %s\n", r.cr, r.resident)
		}
	}
	return nil
}

var nepalZone = time.FixedZone("NPT", 5*3600+45*60)

// stmtLine is one transaction on the generated statement, whole rupees.
type stmtLine struct {
	at       time.Time
	desc     string
	dr, cr   int64
	resident string
}

// esewaCSV lays rows out exactly as eSewa's app export does: CRLF, newest
// first, a running balance, the Total row inside the table, counts below.
func esewaCSV(in []stmtLine, now time.Time) string {
	rows := append([]stmtLine(nil), in...)
	for i := 1; i < len(rows); i++ {
		for j := i; j > 0 && rows[j].at.After(rows[j-1].at); j-- {
			rows[j], rows[j-1] = rows[j-1], rows[j]
		}
	}
	balances := make([]float64, len(rows))
	bal := 1250.5
	for i := len(rows) - 1; i >= 0; i-- {
		bal += float64(rows[i].cr - rows[i].dr)
		balances[i] = bal
	}
	day := func(t time.Time, end bool) string {
		clock := "00:00:00"
		if end {
			clock = "23:59:59"
		}
		return t.Format("Mon Jan 02 ") + clock + " NPT " + t.Format("2006")
	}
	var b strings.Builder
	w := func(s string) { b.WriteString(s + "\r\n") }
	w("Statement Report")
	w("")
	w("From Date," + day(rows[len(rows)-1].at, false) + ",To Date," + day(now, true))
	w("Generated On," + now.Format("2006-01-02 15:04:05") + ",Status,ALL")
	w("Channel,ALL,Dr/Cr,ALL")
	w("Generated by,98XXXXXX01")
	w("")
	w("")
	w("Reference Code,Date Time,Description,Dr.,Cr.,Status,Balance (NPR),Channel")
	var dr, cr int64
	for i, r := range rows {
		dr += r.dr
		cr += r.cr
		w(fmt.Sprintf("%s,%s.0,%s,%d.0,%d.0,COMPLETE,%.1f,App", refCode(), r.at.Format("2006-01-02 15:04:05"), r.desc, r.dr, r.cr, balances[i]))
	}
	w(fmt.Sprintf(",,Total,%d.0,%d.0", dr, cr))
	w("")
	w("")
	w(fmt.Sprintf("Total,%d", len(rows)))
	w("Pending,0")
	w(fmt.Sprintf("Complete,%d", len(rows)))
	w("canceled,0")
	w("Time out,0")
	return b.String()
}

// refCode is an eSewa-looking reference: seven upper-case letters and digits.
func refCode() string {
	const alphabet = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
	b := make([]byte, 7)
	_, _ = rand.Read(b)
	for i := range b {
		b[i] = alphabet[int(b[i])%len(alphabet)]
	}
	return string(b)
}
